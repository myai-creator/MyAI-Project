import streamlit as st

# 1. Настройка внешнего вида страницы
st.set_page_config(page_title="ИИ Ассистент Нова", page_icon="🤖", layout="centered")
st.title("🤖 Всезнающий Ассистент Нова")
st.write("Задайте любой вопрос про Brawl Stars или стихи, и ИИ ответит вам моментально!")

# 2. Инициализация истории сообщений
if "messages" not in st.session_state:
    st.session_state.messages = [
        {"role": "assistant", "content": "Привет! Я ваш всезнающий Ассистент Нова. Я выучил всё про Brawl Stars и готов рассказать про любого персонажа! О чем поговорим?"}
    ]

# 3. Отображение истории сообщений
for message in st.session_state.messages:
    with st.chat_message(message["role"]):
        st.markdown(message["content"])

# 4. Поле ввода для пользователя
if user_query := st.chat_input("Напишите сообщение..."):
    with st.chat_message("user"):
        st.markdown(user_query)
    st.session_state.messages.append({"role": "user", "content": user_query})

    # Генерация ответа из встроенной базы знаний
    with st.chat_message("assistant"):
        with st.spinner("Нова ищет в базе данных..."):
            
            q = user_query.lower()
            
            # Ответ про персонажей Бравл Старс
            if "персонаж" in q or "бравл" in q or "brawl" in q or "боец" in q or "бойцы" in q:
                ai_response = (
                    "Я знаю абсолютно всех бойцов в Brawl Stars! Вот подробный гид по главным редким группам:\n\n"
                    "• Начальные и Редкие (Легко получить): Шелли (крута на ближней дистанции), Кольт (стреляет очередями издалека), Эль Примо (мощный ближний боец с кулаками), Поко (лечит союзников своей музыкой), Роза (включает щит из листьев).\n\n"
                    "• Сверхредкие (Интересные механики): Рико (его пули отскакивают от стен), Дэррил (катится в бочке на врагов), Пенни (ставит стреляющую пушку), Карл (бросает кирку как бумеранг), Джеки (атакует отбойным молотком по кругу).\n\n"
                    "• Эпические (Очень сильные): Пайпер (наносит огромный урон снайперским зонтом), Фрэнк (оглушает врагов тяжелым молотом), Биби (отбивает врагов бейсбольной битой), Эдгар (прыгает прямо на врагов и лечится от ударов).\n\n"
                    "• Мифические и Легендарные (Самые крутые): Мортис (быстро атакует лопатой), Леон (умеет становиться полностью невидимым), Спайк (кидает взрывающиеся кактусы), Ворон (отравляет врагов ядовитыми кинжалами), Кит (запрыгивает на союзников и лечит их).\n\n"
                    "Про какого конкретного персонажа тебе рассказать подробнее? Напиши его имя!"
                )
            # Ответ про стихи
            elif "стих" in q or "поэзия" in q or "рифм" in q:
                ai_response = (
                    "В стенах НИИ родился свет,\n\n"
                    "Ассистент Нова принес ответ.\n\n"
                    "Запрос про Бравл летит вперед,\n\n"
                    "Наука движется в полет!"
                )
            # Ответ на приветствие
            elif "привет" in q or "пр " in q or "здравствуй" in q:
                ai_response = "Приветствую! Я полностью готов к работе. Спроси меня про персонажей Brawl Stars, и я выдам тебе весь список!"
            # Стандартный ответ на любой другой вопрос
            else:
                ai_response = f"Я принял твой запрос: '{user_query}'. Как всезнающий Ассистент Нова, я готов обсудить это! Но лучше всего я разбираюсь в персонажах Brawl Stars и стихах. Напиши, например: 'расскажи про бравл старс'!"

            st.markdown(ai_response)
            
    st.session_state.messages.append({"role": "assistant", "content": ai_response})
